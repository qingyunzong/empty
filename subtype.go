package main

import "fmt"

// Checker decides structural subtyping over a finite interface type graph.
//
// Rules:
//   - width: Sub may declare members Super does not require;
//   - fields are covariant:      Sub.f <: Super.f;
//   - method params contravariant: Super.p <: Sub.p;
//   - method results covariant:    Sub.r <: Super.r;
//   - "any" is the top type; primitives match only themselves;
//   - recursion is handled coinductively (greatest fixed point): a pair
//     already on the assumption stack is treated as compatible.
type Checker struct {
	env *Env
}

func NewChecker(env *Env) *Checker { return &Checker{env: env} }

type pair struct{ sub, sup string }

// edge is one proof obligation generated by a pair, with the member path
// label that leads to it.
type edge struct {
	label string
	next  pair
}

// leafFailure reports whether the pair is an immediately failing leaf
// (no sub-obligations). okLeaf pairs (e.g. identical primitives, or
// super == any) return ("", false) and generate no edges.
func (c *Checker) leafFailure(sub, sup string) (reason string, failed bool) {
	subIf, subIsIf, subPrim, subAny := c.env.lookup(sub)
	supIf, supIsIf, supPrim, supAny := c.env.lookup(sup)
	switch {
	case supAny:
		return "", false
	case subAny:
		return "any is only a subtype of any", true
	case subPrim || supPrim:
		if sub == sup {
			return "", false
		}
		return fmt.Sprintf("primitive mismatch: %s vs %s", sub, sup), true
	case !subIsIf || !supIsIf:
		return fmt.Sprintf("unknown type: %s vs %s", sub, sup), true
	}
	_ = subIf
	_ = supIf
	return "", false
}

// edges returns the sub-obligations of an interface-vs-interface pair.
// Immediate member failures (missing member, kind clash, arity clash) are
// returned as a non-empty reason instead.
func (c *Checker) edges(sub, sup string) ([]edge, string) {
	subIf, _, _, _ := c.env.lookup(sub)
	supIf, _, _, _ := c.env.lookup(sup)
	var out []edge
	for _, name := range memberNames(supIf) {
		supField, supIsField := supIf.Fields[name]
		supSig := supIf.Methods[name]
		subField, subIsField := subIf.Fields[name]
		subSig, subIsMethod := subIf.Methods[name]
		if !subIsField && !subIsMethod {
			return nil, fmt.Sprintf("missing member %q", name)
		}
		if supIsField {
			if !subIsField {
				return nil, fmt.Sprintf("member %q is a field in %s but a method in %s", name, sup, sub)
			}
			out = append(out, edge{label: "." + name, next: pair{subField, supField}})
			continue
		}
		if !subIsMethod {
			return nil, fmt.Sprintf("member %q is a method in %s but a field in %s", name, sup, sub)
		}
		if len(subSig.Params) != len(supSig.Params) {
			return nil, fmt.Sprintf("method %q arity mismatch: %d vs %d params", name, len(subSig.Params), len(supSig.Params))
		}
		for i := range supSig.Params {
			// Contravariant: the supertype's parameter must be usable
			// where the subtype's parameter is expected.
			out = append(out, edge{
				label: fmt.Sprintf(".%s(arg%d)", name, i),
				next:  pair{supSig.Params[i], subSig.Params[i]},
			})
		}
		out = append(out, edge{label: "." + name + "()", next: pair{subSig.Result, supSig.Result}})
	}
	return out, ""
}

// Compatible reports whether sub <: sup under the coinductive (greatest
// fixed point) interpretation of the type graph.
func (c *Checker) Compatible(sub, sup string) bool {
	memo := map[pair]bool{}
	visiting := map[pair]bool{}
	var rec func(sub, sup string) bool
	rec = func(sub, sup string) bool {
		p := pair{sub, sup}
		if v, ok := memo[p]; ok {
			return v
		}
		if visiting[p] {
			// Coinductive hypothesis: assume the pair holds.
			return true
		}
		visiting[p] = true
		ok := true
		if _, failed := c.leafFailure(sub, sup); failed {
			ok = false
		} else if subIf, isIf, _, _ := c.env.lookup(sub); isIf {
			_ = subIf
			edges, reason := c.edges(sub, sup)
			if reason != "" {
				ok = false
			} else {
				for _, e := range edges {
					if !rec(e.next.sub, e.next.sup) {
						ok = false
						break
					}
				}
			}
		}
		delete(visiting, p)
		memo[p] = ok
		return ok
	}
	return rec(sub, sup)
}

// ShortestFailure performs a BFS over the obligation graph and returns the
// shortest member path to an immediate failure, plus its reason. It returns
// found == false when sub <: sup holds. Because compatibility is the
// greatest fixed point of the obligation equations, a pair is incompatible
// exactly when an immediately-failing leaf is reachable, so BFS yields a
// shortest witness.
func (c *Checker) ShortestFailure(sub, sup string) (path []string, reason string, found bool) {
	type node struct {
		p    pair
		path []string
	}
	if r, failed := c.leafFailure(sub, sup); failed {
		return nil, r, true
	}
	visited := map[pair]bool{{sub, sup}: true}
	queue := []node{{p: pair{sub, sup}}}
	for len(queue) > 0 {
		cur := queue[0]
		queue = queue[1:]
		edges, memberErr := c.edges(cur.p.sub, cur.p.sup)
		if memberErr != "" {
			return cur.path, memberErr, true
		}
		for _, e := range edges {
			nextPath := append(append([]string{}, cur.path...), e.label)
			if r, failed := c.leafFailure(e.next.sub, e.next.sup); failed {
				return nextPath, r, true
			}
			if _, isIf, _, supAny := c.env.lookup(e.next.sub); !isIf || supAny {
				continue // ok leaf or non-interface leaf handled above
			}
			if _, supIsIf, _, _ := c.env.lookup(e.next.sup); !supIsIf {
				continue
			}
			if visited[e.next] {
				continue
			}
			visited[e.next] = true
			queue = append(queue, node{p: e.next, path: nextPath})
		}
	}
	return nil, "", false
}
