package markov_test

import (
	"fmt"

	markov "rwchain"
)

func ExampleChain_Report() {
	c, err := markov.NewChain(
		[]string{"A", "B", "T"},
		[][]string{
			{"1/2", "1/2", "0"},
			{"1/3", "0", "2/3"},
			{"0", "0", "1"},
		},
		[]int64{1, 2, 0},
	)
	if err != nil {
		panic(err)
	}
	rep, err := c.Report(c.Index("A"), []int{c.Index("T")}, 3)
	if err != nil {
		panic(err)
	}
	fmt.Print(rep)
	// Output:
	// == 模型 ==
	// 状态: A(收益1), B(收益2), T(收益0)
	// 转移:
	//   A: →A 1/2, →B 1/2
	//   B: →A 1/3, →T 2/3
	//   T: →T 1
	//
	// == 有限步期望（起点 A）==
	// E_0 = 0
	// E_1 = 1
	// E_2 = 5/2
	// E_3 = 41/12
	//
	// == 达到目标 {T} 前的累计收益 ==
	// 方程组 x(i) = 常数项 + Σ p(i,j)·x(j)（目标边界 x=0）:
	//   x(A) = 1 + 1/2·x(A) + 1/2·x(B)
	//   x(B) = 2 + 1/3·x(A)
	// 解:
	//   x(A) = 6
	//   x(B) = 4
	//   x(T) = 0（目标边界）
	//
	// == 封闭类证据 ==
	// 类 {A, B}: 瞬态类
	//   A: 类内转移概率和 = 1, 无离类边
	//   B: 类内转移概率和 = 1/3, 离类边 → [T]
	// 类 {T}: 零收益闭类（含目标）
	//   T: 类内转移概率和 = 1, 无离类边
	//   平稳分布: π(T)=1
	//   平稳平均收益率 μ = 0
	//   结论: μ = 0，类内累计收益有界（零收益）
	//
	// == 独立核对 ==
	// 分数消元残差 max|A·x − b| = 0（精确有理）
	// Bareiss 无分数消元 vs Gauss 分数消元: 一致
	// 短步展开 n=3: 矩阵迭代 E = 41/12, 路径枚举 E = 41/12（一致）
}
