// Package dataeng 顺序读取 LevelDB 式物理分片日志，并在掉电后恢复完整逻辑记录。
//
// 物理布局以本题约定为准：文件按 BlockSize 字节的物理块划分，每个片由 7 字节
// 头（小端 uint32 掩码 CRC、小端 uint16 载荷长、uint8 类型）与载荷组成。片不
// 得跨物理块；块内不足 7 字节的尾部必须全零并跳过；完整零头表示当前块剩余部分
// 全部为零填充，不是空记录。
//
// 只有 CRC 通过且逻辑记录闭合（FULL，或 FIRST…零或多个 MIDDLE…LAST）的记录才
// 会交付给回调，交付时附带全部物理载荷区间与逻辑起始偏移。[Strict] 模式在 EOF
// 遇到残头、残载荷或未闭合记录时报错；[Recovery] 模式仅允许丢弃真实 EOF 处未
// 完成的尾记录并通过截断报告说明，其余损坏一律报错，绝不跳过后冒充成功。
//
// 检查点只能建立在已确认的逻辑记录边界上，绑定已读取文件前缀的物理长度与
// SHA256。回调成功才视为确认；回调失败会立即终止，之后不会再颁发包含失败记录
// 的检查点。恢复时会重新扫描所绑定的整个前缀，核验哈希并确认该位置确为完整逻
// 辑记录边界，而不是仅比较调用方提供的哈希。
