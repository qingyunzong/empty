// Package dataeng 在已解析 TDMS 式段头与元数据的宿主之上，提供可导入的
// 原始通道读取能力：恢复跨段省略的索引与通道活动顺序，校验原始字节布局，
// 并按逻辑样本号随机读取单个样本。本包不做文件管理、容器头解析或波形显示，
// 也不实现字符串通道与 DAQmx。
//
// # 通道身份与索引
//
// 通道身份是宿主给定的非空 UTF-8 路径，本包将其视为不透明字符串，不解析
// 路径文本，也不在不同路径之间借用索引。每次更新为三选一：
//
//   - IndexNew：给出类型（i16/i32/f64bits/timestamp）与每 chunk 正样本数 n，
//     建立或更新该路径的索引缓存。首次 new 固定类型与端序，后续 new 只可改 n。
//   - IndexReuse：沿用该路径最近一次 new 的完整索引；从未 new 过则整段拒绝。
//   - IndexNone：该通道本段无原始数据，但不删除最近一次 new 的缓存。
//
// 类型宽度固定为 2/4/8/16。f64bits 只返回 IEEE 位型 uint64，不做十进制转换；
// timestamp 由先 uint64 亚秒分量、后 int64 秒分量组成，两分量同按段端序解码，
// 精确秒值为 Seconds + Fraction/2^64。
//
// # 活动顺序
//
// NewList=true 时，本段活动顺序恰为更新列表中非 none 路径的出现顺序；
// NewList=false 时继承上段活动顺序，已有路径保持位置，none 移除该路径，
// new/reuse 的未活动路径按更新顺序追加。同段重复路径一律拒绝。
//
// # 原始布局与原子提交
//
// LayoutContiguous 在每个 chunk 内按活动顺序存放各通道的全部 n 个样本；
// LayoutInterleaved 要求所有活动通道 n 相同，按样本序号轮流存放各通道一个值，
// 但不要求类型宽度相同。原始区长度必须是单 chunk 字节数的整数倍，不允许短尾；
// 活动为空时只允许空原始区，空原始区仍可提交元数据。
//
// 一段的全部校验通过后才会原子提交缓存、活动顺序与样本；坏 raw、错误复用或
// 类型冲突使整段不生效，可用原段号重试且不会产生重复样本，已提交段号再次输入
// 一律拒绝。暂停（通道未活动）不补零，改变 n 不会重分旧样本。
//
// # 读取
//
// Engine.Open 按路径与逻辑半开样本号区间返回 Handle。句柄通过宿主提供的
// 不可变 io.ReaderAt 逐值读取，读取单个样本不需要全文件读入；段索引按 chunk
// 保存，不为每个样本各建一项。Result 同时带回值与来源段、chunk、逻辑号和
// 绝对物理字节偏移。预算超限或寻址乘法溢出都在读取前拒绝。
