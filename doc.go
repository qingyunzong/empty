// Package q197 实现网页采集宿主使用的关联数据展开组件。
//
// 组件接收 JSON 树与调用方注入的命名上下文映射（Registry），
// 在本地把词项展开为绝对 IRI，全程不访问外网。上下文支持：
//
//   - 词项到绝对 IRI 的直接映射与词项别名（递归展开，环报完整链）；
//   - "@vocab" 默认词汇前缀，nil 值删除继承的默认前缀；
//   - "@include" 与词项 "@context" 的嵌套作用域覆盖；
//   - null 映射删除继承词项，删除后可在子作用域重新定义。
//
// 编译后的 Scope 不可变并按 (父作用域, 上下文名称) 缓存，
// 同一上下文在不同父作用域下各自复用。展开对象时键冲突会拒绝
// 整个对象，数组顺序与字符串等标量值保持原样。
