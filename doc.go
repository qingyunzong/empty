// Package formal 实现分布式执行引擎调度器调用的任务协调库。
//
// 协调器是一个确定性的事件溯源状态机，提供四项核心能力：
//
//   - 分位数推测：基于历史成功运行时长的最近秩分位数，在慢任务达到
//     SlowQuantile 阈值且仍有尝试配额与空闲执行器时启动有限推测副本；
//   - 首个有效结果提交：首个通过校验的结果提交其 shuffle 分区，并撤销
//     同一任务的其余运行中尝试；
//   - 恰好一次发布：执行器丢失后的晚到成功、提交后的重复结果一律产生
//     ResultRejected 事件，任何分区都不会被发布两次；
//   - 可重放校验：所有状态变更都记录为带序号与时间戳的 Event，通过
//     Replay 可重建状态并校验分区唯一提交、资源计费守恒以及慢任务不被
//     过早判定三类不变量。
//
// 协调器本身不读取系统时钟、不持有 goroutine 或随机源，所有时间均由
// 调用方经方法参数提供，因此同一事件日志的重放结果是确定的。
