// Package dataeng 从自定义二进制归档中逐个采集成员。
//
// 采集过程中每个成员独立判定是否收录：名称非法或超过调用方上限的成员跳过；
// 字节数、摘要不符或同名冲突的成员失败且不保留已读字节；归档在最后一个
// 成员结束前被截断时，此前已通过的成员仍然保留，结果中标记为不完整。
//
// 归档为二进制格式，布局如下：
//
//   - 固定标识头 "ARCV1\n"；
//   - 零条或多条成员记录，依次为 uint32 大端名称长度、名称字节、
//     uint64 大端声明字节数、32 字节 SHA-256 摘要以及正文；
//   - 名称长度为 0 的 4 字节记录作为归档结束标记。
//
// 采集入口为 Collect，归档构造入口为 NewWriter。
